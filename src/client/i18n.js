let active = 'zh';

export function setLocale(locale) {
  const next = String(locale ?? '').toLowerCase();
  active = next.startsWith('zh') ? 'zh' : 'en';
}

export function localeName() { return active; }

export function translate(value) {
  if (active === 'zh' || typeof value !== 'string' || !/[\u3400-\u9fff]/.test(value)) return value;
  const exact = EN[value];
  if (exact !== undefined) return exact;
  if (value.startsWith('无法解析此服务器配置：')) {
    const inner = value.slice('无法解析此服务器配置：'.length);
    return `Could not parse this server configuration: ${EN[inner] ?? inner}`;
  }
  if (value.startsWith('已识别 ')) {
    return value
      .replace(/^已识别 (\d+) 个服务/, 'Recognized $1 services')
      .replace(/待添加 (\d+)/g, 'to add: $1')
      .replace(/已存在跳过 (\d+)/g, 'existing skipped: $1')
      .replace(/重名冲突 (\d+)/g, 'duplicate names: $1')
      .replace(/无法解析 (\d+)/g, 'unparseable: $1')
      .replace(/需核对 (\d+)/g, 'need review: $1');
  }
  if (value.includes('（已测试 ')) {
    const [head, tail] = value.split('（已测试 ');
    const translated = EN[head] ?? head;
    return `${translated}(tested ${tail.replace('）', ')')}`;
  }
  for (const [pattern, replacement] of DYNAMIC) {
    if (pattern.test(value)) return value.replace(pattern, replacement);
  }
  return value;
}

const TEXT_PROPS = new Set(['title', 'placeholder', 'aria-label', 'alt', 'label', 'confirmLabel', 'description']);

function localizeChildren(children) {
  return children.map(child => {
    if (typeof child === 'string') return translate(child);
    if (Array.isArray(child)) return localizeChildren(child);
    return child;
  });
}

/** Create an element with localized text. Used as the JSX factory in App.jsx. */
export function h(type, props, ...children) {
  let nextProps = props;
  if (props && typeof props === 'object') {
    for (const key of TEXT_PROPS) {
      if (typeof props[key] === 'string') {
        if (nextProps === props) nextProps = { ...props };
        nextProps[key] = translate(props[key]);
      }
    }
    if (typeof props.children === 'string' && translate(props.children) !== props.children) {
      if (nextProps === props) nextProps = { ...props };
      nextProps.children = translate(props.children);
    }
  }
  return React.createElement(type, nextProps, ...localizeChildren(children));
}
